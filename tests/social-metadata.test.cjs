const test = require('node:test');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const { createServer } = require('../server.cjs');

test('crawler receives social metadata and a real PNG without executing JavaScript', async t => {
  const server = createServer();
  server.listen(0, '127.0.0.1');
  await once(server, 'listening');
  t.after(() => new Promise(resolve => { server.close(resolve); server.closeAllConnections(); }));
  const base = `http://127.0.0.1:${server.address().port}`;
  const response = await fetch(base, { headers: { 'User-Agent': 'Discordbot/2.0' } });
  assert.equal(response.status, 200);
  const html = await response.text();
  const head = html.split('</head>')[0];
  const metadata = Object.fromEntries([...head.matchAll(/<meta (?:property|name)="([^"]+)" content="([^"]+)"/g)].map(m => [m[1], m[2]]));
  assert.match(head, /<title>Imagecraft — the image mode field guide<\/title>/);
  assert.equal(metadata['og:title'], 'Imagecraft — the image mode field guide');
  assert.equal(metadata['twitter:title'], metadata['og:title']);
  assert.equal(metadata['og:description'], metadata.description);
  assert.equal(metadata['twitter:description'], metadata.description);
  assert.match(metadata.description, /RHEL/);
  assert.match(metadata.description, /recipes/);
  assert.equal(metadata['og:type'], 'website');
  assert.equal(metadata['og:url'], 'https://imagecraft.graa.dev/');
  assert.match(head, /<link rel="canonical" href="https:\/\/imagecraft.graa.dev\/">/);
  assert.equal(metadata['og:image'], 'https://imagecraft.graa.dev/social-preview.png');
  assert.equal(metadata['twitter:image'], metadata['og:image']);
  assert.equal(metadata['twitter:card'], 'summary_large_image');
  assert.equal(metadata['og:image:type'], 'image/png');
  assert.equal(metadata['og:image:width'], '1200');
  assert.equal(metadata['og:image:height'], '630');
  assert.ok(metadata['og:image:alt'].length > 20);
  assert.equal(metadata['twitter:image:alt'], metadata['og:image:alt']);
  const imagePath = new URL(metadata['og:image']).pathname;
  const image = await fetch(base + imagePath, { headers: { 'User-Agent': 'Discordbot/2.0' } });
  assert.equal(image.status, 200);
  assert.equal(image.headers.get('content-type'), 'image/png');
  const bytes = Buffer.from(await image.arrayBuffer());
  assert.deepEqual([...bytes.subarray(0, 8)], [137, 80, 78, 71, 13, 10, 26, 10]);
  assert.equal(bytes.readUInt32BE(16), Number(metadata['og:image:width']));
  assert.equal(bytes.readUInt32BE(20), Number(metadata['og:image:height']));
  const imageHead = await fetch(base + imagePath, { method: 'HEAD' });
  assert.equal(imageHead.status, 200);
  assert.equal(imageHead.headers.get('content-length'), String(bytes.length));
  assert.equal((await imageHead.arrayBuffer()).byteLength, 0);
});
